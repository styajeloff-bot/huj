const CYRILLIC_TO_LATIN: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'i',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'c',
  ч: 'ch',
  ш: 'sh',
  щ: 'shch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
}

/**
 * Transliterates Cyrillic to Latin, converts spaces/underscores to hyphens,
 * strips special characters, and converts to lowercase.
 *
 * Example: "Спецпредложение и лизинг" -> "specpredlozhenie-i-lizing"
 */
export function slugify(text: string): string {
  if (!text) return ''

  const transliterated = Array.from(text.trim().toLowerCase())
    .map((char) => CYRILLIC_TO_LATIN[char] ?? char)
    .join('')

  return transliterated
    .replace(/[\s_]+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
}
